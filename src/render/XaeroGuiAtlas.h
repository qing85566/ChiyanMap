inline ID3D11ShaderResourceView* g_xaeroGuiSRV = nullptr;

inline ID3D11ShaderResourceView* GetXaeroGuiSRV(ID3D11Device* pDevice) {
    if (g_xaeroGuiSRV) return g_xaeroGuiSRV;
    if (!pDevice) return nullptr;

    HRESULT hrCo = CoInitializeEx(nullptr, COINIT_MULTITHREADED);
    bool needUninit = SUCCEEDED(hrCo);

    IWICImagingFactory* pFactory = nullptr;
    HRESULT hr = CoCreateInstance(
        CLSID_WICImagingFactory, nullptr, CLSCTX_INPROC_SERVER,
        IID_PPV_ARGS(&pFactory)
    );
    if (FAILED(hr) || !pFactory) {
        if (needUninit) CoUninitialize();
        return nullptr;
    }

    IStream* pStream = SHCreateMemStream(kXaeroGuiPngData, sizeof(kXaeroGuiPngData));
    if (!pStream) {
        pFactory->Release();
        if (needUninit) CoUninitialize();
        return nullptr;
    }

    IWICBitmapDecoder* pDecoder = nullptr;
    hr = pFactory->CreateDecoderFromStream(
        pStream,
        nullptr,
        WICDecodeMetadataCacheOnDemand,
        &pDecoder
    );
    pStream->Release();

    if (FAILED(hr) || !pDecoder) {
        pFactory->Release();
        if (needUninit) CoUninitialize();
        return nullptr;
    }

    IWICBitmapFrameDecode* pFrame = nullptr;
    hr = pDecoder->GetFrame(0, &pFrame);
    if (FAILED(hr) || !pFrame) {
        pDecoder->Release();
        pFactory->Release();
        if (needUninit) CoUninitialize();
        return nullptr;
    }

    IWICFormatConverter* pConverter = nullptr;
    hr = pFactory->CreateFormatConverter(&pConverter);
    if (FAILED(hr) || !pConverter) {
        pFrame->Release();
        pDecoder->Release();
        pFactory->Release();
        if (needUninit) CoUninitialize();
        return nullptr;
    }

    hr = pConverter->Initialize(
        pFrame,
        GUID_WICPixelFormat32bppRGBA,
        WICBitmapDitherTypeNone,
        nullptr,
        0.0f,
        WICBitmapPaletteTypeCustom
    );
    if (FAILED(hr)) {
        pConverter->Release();
        pFrame->Release();
        pDecoder->Release();
        pFactory->Release();
        if (needUninit) CoUninitialize();
        return nullptr;
    }

    UINT width = 0, height = 0;
    pConverter->GetSize(&width, &height);
    if (width == 0 || height == 0) {
        pConverter->Release();
        pFrame->Release();
        pDecoder->Release();
        pFactory->Release();
        if (needUninit) CoUninitialize();
        return nullptr;
    }

    UINT stride = width * 4;
    UINT bufferSize = stride * height;
    std::vector<BYTE> pixelBuffer(bufferSize);

    hr = pConverter->CopyPixels(nullptr, stride, bufferSize, pixelBuffer.data());
    pConverter->Release();
    pFrame->Release();
    pDecoder->Release();
    pFactory->Release();
    if (needUninit) CoUninitialize();

    if (FAILED(hr)) return nullptr;

    D3D11_TEXTURE2D_DESC desc = {};
    desc.Width = width;
    desc.Height = height;
    desc.MipLevels = 1;
    desc.ArraySize = 1;
    desc.Format = DXGI_FORMAT_R8G8B8A8_UNORM;
    desc.SampleDesc.Count = 1;
    desc.Usage = D3D11_USAGE_DEFAULT;
    desc.BindFlags = D3D11_BIND_SHADER_RESOURCE;

    D3D11_SUBRESOURCE_DATA initData = {};
    initData.pSysMem = pixelBuffer.data();
    initData.SysMemPitch = stride;

    ID3D11Texture2D* pTexture = nullptr;
    hr = pDevice->CreateTexture2D(&desc, &initData, &pTexture);
    if (SUCCEEDED(hr) && pTexture) {
        hr = pDevice->CreateShaderResourceView(pTexture, nullptr, &g_xaeroGuiSRV);
        pTexture->Release();
    }

    return g_xaeroGuiSRV;
}

inline void ReleaseXaeroGuiSRV() {
    if (g_xaeroGuiSRV) {
        g_xaeroGuiSRV->Release();
        g_xaeroGuiSRV = nullptr;
    }
}

